type rawEnvelope struct {
	SchemaVersion string          `json:"schema_version"`
	Command       string          `json:"command"`
	OK            bool            `json:"ok"`
	Partial       bool            `json:"partial"`
	ObservedAt    string          `json:"observed_at"`
	Data          json.RawMessage `json:"data"`
	Diagnostics   []Diagnostic    `json:"diagnostics"`
}

func invokeCommand(t *testing.T, app *App, input string, args ...string) commandInvocation {
	t.Helper()
	var stdout, stderr bytes.Buffer
	app.In = strings.NewReader(input)
	app.Out = &stdout
	app.Err = &stderr
	root := NewRootCommand(app)
	root.SetArgs(args)
	err := root.ExecuteContext(app.Context)
	return commandInvocation{stdout: stdout.String(), stderr: stderr.String(), err: err}
}

func decodeEnvelope(t *testing.T, output string) rawEnvelope {
	t.Helper()
	decoder := json.NewDecoder(strings.NewReader(output))
	var envelope rawEnvelope
	if err := decoder.Decode(&envelope); err != nil {
		t.Fatalf("decode envelope %q: %v", output, err)
	}
	var trailing any
	if err := decoder.Decode(&trailing); !errors.Is(err, io.EOF) {
		t.Fatalf("machine stdout has trailing content %q: %v", output, err)
	}
	var fields map[string]json.RawMessage
	if err := json.Unmarshal([]byte(output), &fields); err != nil {
		t.Fatal(err)
	}
	if _, old := fields["schema"]; old {
		t.Fatalf("machine envelope supports obsolete schema field: %s", output)
	}
	if envelope.SchemaVersion != MachineSchema || envelope.Diagnostics == nil || !strings.Contains(output, `"diagnostics":[`) {
		t.Fatalf("unstable machine envelope = %#v\n%s", envelope, output)
	}
	return envelope
}

func decodeData(t *testing.T, envelope rawEnvelope, destination any) {
	t.Helper()
	if err := json.Unmarshal(envelope.Data, destination); err != nil {
		t.Fatalf("decode %s data %s: %v", envelope.Command, envelope.Data, err)
	}
}

func requireCommandSuccess(t *testing.T, invocation commandInvocation) {
	t.Helper()
	if invocation.err != nil {
		t.Fatalf("command error = %v, stdout=%q stderr=%q", invocation.err, invocation.stdout, invocation.stderr)
	}
	envelope := decodeEnvelope(t, invocation.stdout)
	if !envelope.OK {
		t.Fatalf("command returned non-ok envelope: %#v", envelope)
	}
}

func deterministicApp(t *testing.T, ids ...string) *App {
	t.Helper()
	app := NewApp(t.Context(), nil, nil, nil)
	app.Now = func() time.Time { return time.Date(2026, 8, 29, 12, 0, 0, 0, time.UTC) }
	if len(ids) > 0 {
		generator, _ := uuidGeneratorSequence(t, ids...)
		app.GenerateUUID = generator
	}
	return app
}

func uuidGeneratorSequence(t *testing.T, values ...string) (research.UUIDGenerator, *int) {
	t.Helper()
	parsed := make([]uuid.UUID, len(values))
	for index, value := range values {
		parsed[index] = uuid.MustParse(value)
	}
	var mutex sync.Mutex
	calls := 0
	generator := research.UUIDGenerator(func(time.Time) (uuid.UUID, error) {
		mutex.Lock()
		defer mutex.Unlock()
		if calls >= len(parsed) {
			t.Fatalf("UUID generator call %d exceeds %d configured values", calls+1, len(parsed))
		}
		value := parsed[calls]
		calls++
		return value, nil
	})
	return generator, &calls
}

func newGitRepository(t *testing.T) string {
	t.Helper()
	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("USERPROFILE", home)
	repository := filepath.Join(t.TempDir(), "repo")
	if err := os.Mkdir(repository, 0o755); err != nil {
		t.Fatal(err)
	}
	command := exec.Command("git", "init", "--quiet")
	command.Dir = repository
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("git init: %v\n%s", err, output)
	}
	canonical, err := filepath.EvalSymlinks(repository)
	if err != nil {
		t.Fatal(err)
	}
	return canonical
}

