type blockingClosableReader struct {
	startedOnce sync.Once
	closedOnce  sync.Once
	started     chan struct{}
	closed      chan struct{}
	finished    chan struct{}
}

func (reader *blockingClosableReader) Read([]byte) (int, error) {
	reader.startedOnce.Do(func() { close(reader.started) })
	<-reader.closed
	close(reader.finished)
	return 0, io.EOF
}

func (reader *blockingClosableReader) Close() error {
	reader.closedOnce.Do(func() { close(reader.closed) })
	return nil
}

func TestInitCreatesAllProjectionsIsIdempotentAndChecksDrift(t *testing.T) {
	repository := newGitRepository(t)
	fixedTime := time.Date(2026, 8, 29, 10, 11, 12, 0, time.UTC)
	generator, calls := uuidGeneratorSequence(t,
		"01a01e60-0000-7101-8000-000000000101",
	)
	app := NewApp(t.Context(), nil, nil, nil)
	app.Now = func() time.Time { return fixedTime }
	app.GenerateUUID = generator

	first := invokeCommand(t, app, "", "--start-dir", repository, "init", "--name", "Command Study", "--json")
	if first.err != nil {
		t.Fatalf("init error = %v, stderr = %q", first.err, first.stderr)
	}
	envelope := decodeEnvelope(t, first.stdout)
	if !envelope.OK || envelope.SchemaVersion != MachineSchema || *calls != 1 {
		t.Fatalf("first init envelope=%#v generator calls=%d", envelope, *calls)
	}
	var data initData
	decodeData(t, envelope, &data)
	if !data.Created || data.Project.Name != "Command Study" || len(data.Projections.Written) != 4 {
		t.Fatalf("first init data = %#v", data)
	}
	if data.Project.RepositoryRoot != repository || data.Project.Root != filepath.Join(repository, "experiments") {
		t.Fatalf("safe project paths changed: %#v", data.Project)
	}
	for _, name := range projection.Paths() {
		content, err := os.ReadFile(filepath.Join(data.Project.Root, name))
		if err != nil {
			t.Fatalf("read %s: %v", name, err)
		}
		if !bytes.HasPrefix(content, []byte("<!-- Generated by exp render; DO NOT EDIT. -->\n")) {
			t.Fatalf("%s is not a generated projection: %q", name, content)
		}
	}

	second := invokeCommand(t, app, "", "--start-dir", filepath.Join(repository, "experiments"), "init", "--name", "Ignored", "--json")
	if second.err != nil {
		t.Fatal(second.err)
	}
	secondEnvelope := decodeEnvelope(t, second.stdout)
	decodeData(t, secondEnvelope, &data)
	if data.Created || data.Project.Name != "Command Study" || data.Projections.Changed || *calls != 1 {
		t.Fatalf("idempotent init data=%#v calls=%d", data, *calls)
	}

	readme := filepath.Join(data.Project.Root, projection.READMEFile)
	if err := os.WriteFile(readme, []byte("stale\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	before, err := os.ReadFile(readme)
	if err != nil {
		t.Fatal(err)
	}
	checked := invokeCommand(t, app, "", "--start-dir", repository, "render", "--check", "--json")
	if !errors.Is(checked.err, projection.ErrStale) {
		t.Fatalf("render --check error = %v", checked.err)
	}
	checkedEnvelope := decodeEnvelope(t, checked.stdout)
	if checkedEnvelope.OK || len(checkedEnvelope.Diagnostics) != 1 || checkedEnvelope.Diagnostics[0].Path != projection.READMEFile {
		t.Fatalf("stale envelope = %#v", checkedEnvelope)
	}
	var checkedData renderData
	decodeData(t, checkedEnvelope, &checkedData)
	if !reflect.DeepEqual(checkedData.Result.Drifted, []string{projection.READMEFile}) || checkedData.Result.Changed || len(checkedData.Result.Written) != 0 {
		t.Fatalf("stale result = %#v", checkedData.Result)
	}
	afterCheck, err := os.ReadFile(readme)
	if err != nil || !bytes.Equal(before, afterCheck) {
		t.Fatalf("render --check wrote README: %q, %v", afterCheck, err)
	}

	repaired := invokeCommand(t, app, "", "--start-dir", repository, "render", "--json")
	if repaired.err != nil {
		t.Fatal(repaired.err)
	}
	repairedEnvelope := decodeEnvelope(t, repaired.stdout)
	var repairedData renderData
	decodeData(t, repairedEnvelope, &repairedData)
	if !repairedData.Result.Current || !reflect.DeepEqual(repairedData.Result.Written, []string{projection.READMEFile}) {
		t.Fatalf("render repair = %#v", repairedData.Result)
	}
}

