	if err != nil {
		t.Fatal(err)
	}
	repository = canonical
	expectedRepository := strings.Replace(repository, credentialComponent, safex.Redacted, 1)
	if expectedRepository == repository {
		t.Fatalf("test repository %q does not contain credential component", repository)
	}

	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("USERPROFILE", home)
	app := deterministicApp(t, "01a01e60-0000-7101-8000-000000000101")
